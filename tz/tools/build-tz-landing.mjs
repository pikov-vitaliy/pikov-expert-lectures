function esc(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function p(text) {
  return `<p>${text}</p>`;
}

function callout(kind, title, text) {
  return `<div class="callout ${kind}">
    <div class="callout-mark" aria-hidden="true">${kind === 'danger' ? '!' : kind === 'success' ? '✓' : kind === 'warning' ? '?' : 'i'}</div>
    <div class="callout-body"><strong>${title}</strong>${text}</div>
  </div>`;
}

function cards(items, cols = 3) {
  return `<div class="grid cols-${cols}">${items.map((item, index) => `<article class="card">
    <div class="card-num">${String(index + 1).padStart(2, '0')}</div>
    <h3>${item.title}</h3>
    <p>${item.text}</p>
  </article>`).join('')}</div>`;
}

function checklist(items, kind = '') {
  return `<ul class="checklist ${kind}">${items.map(item => `<li>${item}</li>`).join('')}</ul>`;
}

function numberList(items) {
  return `<ol class="numlist">${items.map(item => `<li>${item}</li>`).join('')}</ol>`;
}

function table(headers, rows) {
  return `<div class="tbl-wrap"><table class="tbl">
    <thead><tr>${headers.map(h => `<th>${h}</th>`).join('')}</tr></thead>
    <tbody>${rows.map(row => `<tr>${row.map(cell => `<td>${cell}</td>`).join('')}</tr>`).join('')}</tbody>
  </table></div>`;
}

function split(left, right) {
  return `<div class="split"><div>${left}</div><div>${right}</div></div>`;
}

function flow(items) {
  return `<div class="flow">${items.map(item => `<div class="flow-item">${item}</div>`).join('')}</div>`;
}

function codeBlock(code) {
  return `<pre class="code"><code>${esc(code)}</code></pre>`;
}

function bigStatement(text, note = '') {
  return `<div class="big-statement"><strong>${text}</strong>${note ? `<span>${note}</span>` : ''}</div>`;
}


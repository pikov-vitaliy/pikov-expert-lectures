function renderSlide(slide, index) {
  const n = index + 1;
  const titleTag = slide.tone === 'cover' ? 'h1' : 'h2';
  const tone = slide.tone ? ` ${slide.tone}` : '';
  return `<section class="slide${tone}" id="slide-${n}" data-block="${esc(slide.block)}" data-screen-label="${esc(slide.label)}">
    <div class="slide-inner">
      <span class="eyebrow">${slide.eyebrow}</span>
      <${titleTag} class="${slide.tone === 'cover' ? 'hero-title' : ''}">${slide.title}</${titleTag}>
      <p class="lead">${slide.lead}</p>
      ${slide.body}
      <div class="slide-meta"><span class="block-tag">${slide.block}</span><span>${String(n).padStart(2, '0')} / ${slides.length}</span></div>
    </div>
  </section>`;
}


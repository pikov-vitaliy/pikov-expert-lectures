using System;

class CopyName
{
    static void Main()
    {
        Console.OutputEncoding = System.Text.Encoding.UTF8;

        char[] buffer = new char[16];   // буфер: ровно 16 символов
        string source = "Иванова Анна Петровна, отдел информационной безопасности";

        Console.WriteLine($"Длина исходной строки: {source.Length}");
        Console.WriteLine($"Размер буфера:         {buffer.Length}");
        Console.WriteLine();

        try
        {
            // Тот же цикл, та же логическая ошибка: идём по длине источника.
            for (int i = 0; i < source.Length; i++)
            {
                buffer[i] = source[i];
            }
            Console.WriteLine("Скопировано без ошибок — этого не произойдёт.");
        }
        catch (IndexOutOfRangeException error)
        {
            Console.WriteLine("Среда выполнения остановила запись за границу буфера:");
            Console.WriteLine($"    {error.Message}");
        }

        // -------------------------------------------------------------------
        // А вот как эта задача решается правильно. Обратите внимание:
        // цикл ограничен МЕНЬШЕЙ из двух длин, а не длиной источника.
        // -------------------------------------------------------------------
        int limit = Math.Min(source.Length, buffer.Length);
        for (int i = 0; i < limit; i++)
        {
            buffer[i] = source[i];
        }
        Console.WriteLine($"Безопасная копия: «{new string(buffer, 0, limit)}»");
    }
}


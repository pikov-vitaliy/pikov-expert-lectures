//
//  Проверку границ массива в C# нельзя отключить настройкой сборки.
//  Она встроена в среду выполнения (CLR) и работает всегда — в отличие
//  от {$RANGECHECKS} в Pascal, который можно выключить.
//
//  В самом управляемом массиве проверка сохраняется. Отдельную границу
//  создают unsafe-код, FFI/P/Invoke и нативные зависимости: они требуют
//  разрешения сборки, ревью и собственных мер контроля.
//  Именно поэтому в правилах кодирования (процесс 5.8 ГОСТ Р 56939-2024)
//  для C#-проектов обычно прямо записывают: «блоки unsafe запрещены,
//  исключения согласуются с архитектором».
//
//  Языки, где безопасность памяти обеспечивается средой выполнения или
//  компилятором, называют memory-safe: C#, Java, Python, Go, Rust.
//  Языки, где она лежит на программисте: C, C++, ассемблер.
//  По данным Microsoft Security Response Center, около 70 % уязвимостей

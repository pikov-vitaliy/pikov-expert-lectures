#
#  1. Ошибка выхода за границу обнаруживается всегда и отключить проверку
#     нельзя — как в C#, в отличие от Pascal.
#
#  2. У строк в Python вообще нет фиксированного размера. «Буфер на 16
#     символов» пришлось изображать списком: сама задача в этом языке
#     обычно не возникает. Целый класс уязвимостей исчезает вместе
#     с ручным управлением памятью.
#
#  3. Плата за это — производительность и потеря контроля над тем, где
#     и как размещаются данные. Поэтому загрузчики, драйверы и ядра
#     операционных систем на Python не пишут.
